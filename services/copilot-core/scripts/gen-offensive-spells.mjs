#!/usr/bin/env node
/**
 * Writes src/fight/offensiveSpells.ts: the spells of the game that attack a creature (`target` 1, `TAR_CHAR_OFFENSIVE` in merc.h), read from
 * merc-area's stock skill table, which is itself generated from merc-mud/2.4/src/const.c. Copilot must not start a fight blind, and `cast
 * <spell> <target>` is a fight only when the spell is offensive (`cast heal <friend>` is not).
 *
 *   node services/copilot-core/scripts/gen-offensive-spells.mjs
 *
 * Run it after the stock table changes and review the diff. This package has no dependency on merc-area; only this script reads its file.
 */
/* global console, process */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, '..', '..', 'merc-area', 'src', 'skills-stock.ts');
const target = path.join(here, '..', 'src', 'fight', 'offensiveSpells.ts');

/** The names of the stock rows whose target is `TAR_CHAR_OFFENSIVE` and that are spells (a skill has the null spell function). */
export function offensiveSpells(text) {
  const names = [];
  const row = /\{ name: "([^"]+)", spellFun: "([^"]+)", target: (\d+),/g;
  for (let m = row.exec(text); m !== null; m = row.exec(text)) if (m[3] === '1' && m[2] !== 'spell_null') names.push(m[1]);
  return names.sort();
}

export function render(names) {
  return `/**
 * GENERATED by services/copilot-core/scripts/gen-offensive-spells.mjs from merc-area's stock skill table (merc-mud/2.4/src/const.c skill_table):
 * the spells whose target is TAR_CHAR_OFFENSIVE (merc.h). Do not hand-edit.
 */
export const OFFENSIVE_SPELLS: readonly string[] = [
${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
];
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const names = offensiveSpells(fs.readFileSync(source, 'utf8'));
  if (names.length === 0) throw new Error('no offensive spells found: the stock table changed shape');
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, render(names), 'utf8');
  console.log(`wrote ${names.length} offensive spells to ${path.relative(process.cwd(), target)}`);
}
