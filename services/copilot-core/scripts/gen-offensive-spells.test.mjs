import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { offensiveSpells, render } from './gen-offensive-spells.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));

const TABLE = `
  { name: "armor", spellFun: "spell_armor", target: 2, position: 8 },
  { name: "fireball", spellFun: "spell_fireball", target: 1, position: 7 },
  { name: "acid blast", spellFun: "spell_acid_blast", target: 1, position: 7 },
  { name: "bash", spellFun: "spell_null", target: 1, position: 7 },
  { name: "call lightning", spellFun: "spell_call_lightning", target: 0, position: 7 },
`;

test('offensiveSpells takes the rows with an offensive target that are spells, sorted', () => {
  assert.deepEqual(offensiveSpells(TABLE), ['acid blast', 'fireball']);
  assert.deepEqual(offensiveSpells('nothing here'), []);
});

test('render writes a list a reader can import, with the generated notice', () => {
  const text = render(['acid blast', 'fireball']);
  assert.match(text, /GENERATED by services\/copilot-core\/scripts\/gen-offensive-spells\.mjs/);
  assert.match(text, /export const OFFENSIVE_SPELLS: readonly string\[\] = \[\n {2}"acid blast",\n {2}"fireball",\n\];/);
});

test('the checked-in list is what the stock table gives now (run the generator after the table changes)', () => {
  const stock = path.join(here, '..', '..', 'merc-area', 'src', 'skills-stock.ts');
  const checkedIn = fs.readFileSync(path.join(here, '..', 'src', 'fight', 'offensiveSpells.ts'), 'utf8');
  assert.equal(checkedIn, render(offensiveSpells(fs.readFileSync(stock, 'utf8'))));
});
