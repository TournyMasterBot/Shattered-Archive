function isRecord(x: unknown): x is Record<string, unknown> {
  return typeof x === 'object' && x !== null;
}

const ACTION_TYPES = new Set(['move', 'attack', 'ability', 'set-stance', 'end-turn']);

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: looksLikeAction — (no summary)
// @ai-hash: 9e957099
// ── END AI-METHOD ──
/** Shallow structural check that `action` looks like an engine Action (the reducer does
 * the deep legality check). */
function looksLikeAction(x: unknown): x is Action {
  return isRecord(x) && typeof x.type === 'string' && ACTION_TYPES.has(x.type);
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: isKtClientMessage — (no summary)
// @ai-hash: 141531e5
// ── END AI-METHOD ──
/** Type guard for a well-formed client message. Rejects anything with a missing/unknown
 * `type` or missing required fields — safe to run on raw socket input. */
export function isKtClientMessage(x: unknown): x is KtClientMessage {
  if (!isRecord(x) || typeof x.type !== 'string') return false;
  switch (x.type) {
    case 'join':
      return (
        typeof x.matchId === 'string' &&
        (x.side === undefined || typeof x.side === 'number') &&
        (x.token === undefined || typeof x.token === 'string')
      );
    case 'action':
      return typeof x.matchId === 'string' && looksLikeAction(x.action);
    case 'requestSnapshot':
    case 'leave':
      return typeof x.matchId === 'string';
    default:
      return false;
  }
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: parseKtClientMessage — (no summary)
// @ai-hash: c1547fd0
// ── END AI-METHOD ──
/** Parse a raw socket frame into a validated `KtClientMessage`, or `null` if the JSON is
 * malformed or the shape is invalid. Never throws. */
export function parseKtClientMessage(raw: string): KtClientMessage | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  return isKtClientMessage(parsed) ? parsed : null;
}

// ─────────────────────────────────────────────────────────────────────────────
// Parsing / validation (server → client; the client treats server frames defensively too)
// ─────────────────────────────────────────────────────────────────────────────

/** Shallow structural check that `state` looks like a serialized `MatchState`. The reducer /
 * renderer do the real work; here we only guard against obviously-wrong frames. */
function looksLikeState(x: unknown): x is MatchState {
  return isRecord(x) && typeof (x as { activeSide?: unknown }).activeSide === 'number';
}

/** A winner is a seat index or the literal `'draw'`. */
function looksLikeWinner(x: unknown): x is Side | 'draw' {
  return typeof x === 'number' || x === 'draw';
}

/** Type guard for a well-formed server message. Mirrors {@link isKtClientMessage}: rejects a
 * missing/unknown `type` or any variant missing its required fields. Safe on raw socket input. */
export function isKtServerMessage(x: unknown): x is KtServerMessage {
  if (!isRecord(x) || typeof x.type !== 'string') return false;
  switch (x.type) {
    case 'joined':
      return (
        typeof x.matchId === 'string' &&
        typeof x.side === 'number' &&
        looksLikeState(x.state) &&
        typeof x.protocol === 'number'
      );
    case 'snapshot':
      return (
        typeof x.matchId === 'string' &&
        looksLikeState(x.state) &&
        (x.lastAction === undefined || looksLikeAction(x.lastAction))
      );
    case 'error':
      return typeof x.message === 'string' && (x.matchId === undefined || typeof x.matchId === 'string');
    case 'over':
      return typeof x.matchId === 'string' && looksLikeState(x.state) && looksLikeWinner(x.winner);
    default:
      return false;
  }
}

/** Parse a raw socket frame into a validated `KtServerMessage`, or `null` if the JSON is
 * malformed or the shape is invalid. Never throws. Symmetric to {@link parseKtClientMessage}. */
export function parseKtServerMessage(raw: string): KtServerMessage | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  return isKtServerMessage(parsed) ? parsed : null;
}
