import type { Action, MatchState, Side } from '../model/index.js';

/**
 * The `/ws/kt` wire contract, shared by the Kingdom Tactics client and server so the two
 * cannot drift. It lives in the engine because the engine is the isomorphic package both
 * apps already depend on. `MatchState` is a serializable readonly value, so a snapshot IS
 * the state — no custom codec in v1 (see Phase-4 plan, decision 1). Bump `KT_PROTOCOL_VERSION`
 * on any breaking change to these shapes.
 */
export const KT_PROTOCOL_VERSION = 1 as const;

// ─────────────────────────────────────────────────────────────────────────────
// Client → server
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Join (or create) a match and claim a seat. `side` omitted = server assigns.
 * `token` (Phase F) is an optional hub bearer token — the server introspects
 * it to attach an accountId to the claimed seat for history/persistence.
 * Additive only: omitting it is identical to today's fully anonymous join,
 * and an invalid/expired token degrades to anonymous rather than rejecting
 * the join.
 */
export interface KtJoinMessage {
  readonly type: 'join';
  readonly matchId: string;
  readonly side?: Side;
  readonly token?: string;
}

/** Submit an intent; the server validates seat ownership + engine legality. */
export interface KtActionMessage {
  readonly type: 'action';
  readonly matchId: string;
  readonly action: Action;
}

/** Ask the server to re-send the current snapshot. */
export interface KtRequestSnapshotMessage {
  readonly type: 'requestSnapshot';
  readonly matchId: string;
}

/** Release the seat / leave the match. */
export interface KtLeaveMessage {
  readonly type: 'leave';
  readonly matchId: string;
}

export type KtClientMessage =
  | KtJoinMessage
  | KtActionMessage
  | KtRequestSnapshotMessage
  | KtLeaveMessage;

// ─────────────────────────────────────────────────────────────────────────────
// Server → client
// ─────────────────────────────────────────────────────────────────────────────

/** Confirms a join: the seat granted + the current state + the protocol version. */
export interface KtJoinedMessage {
  readonly type: 'joined';
  readonly matchId: string;
  readonly side: Side;
  readonly state: MatchState;
  readonly protocol: number;
}

/** A new authoritative snapshot after an applied action (v1: full state, not a delta). */
export interface KtSnapshotMessage {
  readonly type: 'snapshot';
  readonly matchId: string;
  readonly state: MatchState;
  readonly lastAction?: Action;
}

/** A rejected message / illegal action / protocol error. */
export interface KtErrorMessage {
  readonly type: 'error';
  readonly matchId?: string;
  readonly message: string;
}

/** The match is decided; carries the final state + winner. */
export interface KtOverMessage {
  readonly type: 'over';
  readonly matchId: string;
  readonly state: MatchState;
  readonly winner: Side | 'draw';
}

export type KtServerMessage =
  | KtJoinedMessage
  | KtSnapshotMessage
  | KtErrorMessage
  | KtOverMessage;

