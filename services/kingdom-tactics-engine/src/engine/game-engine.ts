/**
 * The deterministic reducer: apply one `Action` to a `MatchState` and return the NEW
 * state. Pure — never mutates the input, no wall-clock, no I/O; all randomness comes
 * from `rng` and is captured back into `rngState`. Illegal actions (wrong side, spent
 * budget, illegal destination/target, unknown ability) return the input unchanged.
 * See plan p3, decisions 1–6 for the turn semantics.
 */
export function applyAction(
  state: MatchState,
  action: Action,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  if (state.status === 'decided') return state;
  switch (action.type) {
    case 'move':
      return applyMove(state, action, rng, p);
    case 'attack':
      return applyAttackAction(state, action, rng, p);
    case 'ability':
      return applyAbilityAction(state, action, rng, p);
    case 'set-stance':
      return applySetStance(state, action, rng, p);
    case 'end-turn':
      return applyEndTurn(state, action, rng, p);
    default:
      return state;
  }
}

