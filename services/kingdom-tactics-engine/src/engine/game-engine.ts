/** Run the passive/aura trigger hook (if any), then finalize. For real actions only. */
function afterAction(
  state: MatchState,
  action: Action,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  const triggered = p.triggers ? p.triggers(state, { type: 'post-action', action }) : state;
  return finalize(triggered, rng, p);
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: applyMove — (no summary)
// @ai-hash: 901ec49e
// ── END AI-METHOD ──
function applyMove(
  state: MatchState,
  action: MoveAction,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  const token = state.tokens.find((t) => t.instanceId === action.tokenId);
  if (!token) return state;
  if (token.side !== state.activeSide) return state;
  if (!isLiving(token)) return state;
  if (isLockedOut(state, action.tokenId)) return state; // one-unit-per-turn lock
  if (token.hasMoved) return state;
  if (!legalMoves(state, action.tokenId, p.data).some((c) => coordEquals(c, action.to))) {
    return state;
  }
  const tokens = state.tokens.map((t) =>
    t.instanceId === action.tokenId ? moveToken(t, action.to) : t,
  );
  return afterAction({ ...state, tokens, activatedTokenId: action.tokenId }, action, rng, p);
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: applyAttackAction — (no summary)
// @ai-hash: 88d6d453
// ── END AI-METHOD ──
function applyAttackAction(
  state: MatchState,
  action: AttackAction,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  const token = state.tokens.find((t) => t.instanceId === action.tokenId);
  if (!token) return state;
  if (token.side !== state.activeSide) return state;
  if (!isLiving(token)) return state;
  if (isLockedOut(state, action.tokenId)) return state; // one-unit-per-turn lock
  if (token.hasActed) return state;
  // applyAttack validates legalTargets + resolves damage + sets hasActed (preserving
  // hasMoved since it only spreads the token). Illegal target → same ref → no-op.
  // Opt-in per-hit reactions: pass combatHooks + the server-only salted stream when supplied.
  const hookRng = p.combatHooks ? combatRngFor(state, action, rng, p) : rng;
  const next = applyAttack(state, action.tokenId, action.targetId, p.data, hookRng, p.combatHooks);
  if (next === state) return state;
  return afterAction({ ...next, activatedTokenId: action.tokenId }, action, rng, p);
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: applyAbilityAction — (no summary)
// @ai-hash: 658308be
// ── END AI-METHOD ──
function applyAbilityAction(
  state: MatchState,
  action: AbilityAction,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  const token = state.tokens.find((t) => t.instanceId === action.tokenId);
  if (!token) return state;
  if (token.side !== state.activeSide) return state;
  if (!isLiving(token)) return state;
  if (isLockedOut(state, action.tokenId)) return state; // one-unit-per-turn lock
  if (token.hasActed) return state;
  // v1: abilities are a no-op unless a resolver maps the key AND a token target is given.
  if (!p.abilityResolver || typeof action.target !== 'string') return state;
  const spec = p.abilityResolver(action.abilityKey);
  if (!spec) return state;
  const hookRng = p.combatHooks ? combatRngFor(state, action, rng, p) : rng;
  const next = applyAbility(state, action.tokenId, action.target, spec, p.data, hookRng, p.combatHooks);
  if (next === state) return state;
  return afterAction({ ...next, activatedTokenId: action.tokenId }, action, rng, p);
}

/**
 * Set a unit's combat stance — a FREE minor action. Unlike move/attack/ability it does NOT
 * consume `hasMoved`/`hasActed`, does NOT set `activatedTokenId`, and is EXEMPT from the
 * one-unit-per-turn lock: a player may re-stance any/all of their own living units, then still
 * activate one to move + attack. Only the ACTIVE side's own living UNIT tokens (squadrons are
 * stanceless), and only stances legal for the unit's class (Brewmaster stances gated to Brewmasters).
 */
function applySetStance(
  state: MatchState,
  action: SetStanceAction,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  const token = state.tokens.find((t) => t.instanceId === action.tokenId);
  if (!token) return state;
  if (token.kind !== 'unit') return state; // stances are per-unit
  if (token.side !== state.activeSide) return state; // your own units, on your turn only
  if (!isLiving(token)) return state;
  const classKey = token.templateId.split(':')[1] ?? '';
  if (!isStanceLegalFor(action.stance, classKey)) return state;
  if (token.stance === action.stance) return state; // no-op change
  const tokens = state.tokens.map((t) =>
    t.instanceId === action.tokenId && t.kind === 'unit' ? { ...t, stance: action.stance } : t,
  );
  // Free minor action: no activatedTokenId, no trigger hook — just persist + re-check victory.
  return finalize({ ...state, tokens }, rng, p);
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: applyEndTurn — (no summary)
// @ai-hash: 3474a324
// ── END AI-METHOD ──
function applyEndTurn(
  state: MatchState,
  action: EndTurnAction,
  rng: ISeededRng,
  p: EngineProviders,
): MatchState {
  if (action.side !== state.activeSide) return state;
  const next = nextActiveSide(state);
  // Fresh budgets for the incoming side's living tokens.
  const tokens = state.tokens.map((t) =>
    t.side === next && isLiving(t) ? resetFlags(t) : t,
  );
  // A full round completes when play wraps back to the lowest living side.
  const livingSides = new Set<Side>();
  for (const t of tokens) if (isLiving(t)) livingSides.add(t.side);
  const wrapped = livingSides.size > 0 && next === Math.min(...livingSides);
  const advanced: MatchState = {
    ...state,
    tokens,
    activeSide: next,
    activatedTokenId: undefined, // the new side hasn't activated a unit yet
    turn: wrapped ? state.turn + 1 : state.turn,
  };
  // No trigger hook on end-turn (it is not a "post-action" event); victory still re-checked.
  return finalize(advanced, rng, p);
}

