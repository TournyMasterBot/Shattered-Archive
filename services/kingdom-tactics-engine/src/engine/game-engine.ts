/** Move a token to a new tile, consuming its MOVE budget (leaves hasActed alone). */
const moveToken = (t: BoardToken, to: Coord): BoardToken =>
  t.kind === 'unit'
    ? { ...t, pos: to, hasMoved: true }
    : { ...t, pos: to, hasMoved: true };

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
