// ── END AI-METHOD ──
/** Clear BOTH per-turn budgets on a token (used when a side's turn begins). */
const resetFlags = (t: BoardToken): BoardToken =>
  t.kind === 'unit'
    ? { ...t, hasMoved: false, hasActed: false }
    : { ...t, hasMoved: false, hasActed: false };

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: finalize — (no summary)
// @ai-hash: d58e1dbf
// ── END AI-METHOD ──
/**
 * Persist the RNG state and re-check victory. Called after every applied action
 * (including end-turn — victory is re-checked every action per plan decision 2).
 */
function finalize(state: MatchState, rng: ISeededRng, p: EngineProviders): MatchState {
  const withRng: MatchState = { ...state, rngState: rng.state() };
  const victory = evaluateVictory(withRng, p.modes.mode(withRng.modeId), p.data);
  if (victory.decided) {
    return { ...withRng, status: 'decided', winner: victory.winner };
  }
  return withRng;
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: afterAction — (no summary)
// @ai-hash: b487d19e
