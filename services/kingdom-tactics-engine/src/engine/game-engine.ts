/** A living token = unit with hp > 0 / squadron with hpPool > 0. */
function isLiving(t: BoardToken): boolean {
  return t.kind === 'unit' ? t.hp > 0 : t.hpPool > 0;
}

/**
 * One-unit-per-turn lock: once the active side has activated a token this turn
 * (`activatedTokenId`), every OTHER token is locked out until the turn passes.
 */
function isLockedOut(state: MatchState, tokenId: string): boolean {
  return state.activatedTokenId !== undefined && state.activatedTokenId !== tokenId;
}

