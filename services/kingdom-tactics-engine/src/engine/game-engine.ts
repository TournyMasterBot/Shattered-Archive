/**
 * The provider bundle the reducer needs. `data` + `modes` are the Phase-1/2 providers;
 * the two optional hooks are the v1 seams for content that is NOT part of the action
 * economy (see plan p3, decisions 3 + 6):
 *  - `abilityResolver` turns an `abilityKey` into a castable `AbilitySpec` (no catalog in
 *    v1, so abilities are a no-op unless a resolver is supplied);
 *  - `triggers` fires once AFTER each applied non-end-turn action for passive/aura/banter
 *    effects — coarse (per-action), distinct from the fine per-hit combat reactions that
 *    live in the damage layer.
 *  - `combatHooks` are those FINE per-hit reactions (dodge/parry/block, typed shields, thorns);
 *    absent ⇒ Phase-2b damage unchanged. `combatRng` supplies the SERVER-ONLY salted, step-counted
 *    stream those hooks roll against — when present the reducer sources the hooks' rng from it (per
 *    action) instead of the public `MatchState.rngState`, so a client cannot predict avoidance.
 *    Only the server supplies these (see the combat-reactions plan); pure engine/sim use omits them.
 */
export interface EngineProviders {
  readonly data: IGameDataProvider;
  readonly modes: IGameModeProvider;
  readonly abilityResolver?: (key: string) => AbilitySpec | undefined;
  readonly triggers?: (
    state: MatchState,
    ev: { readonly type: 'post-action'; readonly action: Action },
  ) => MatchState;
  readonly combatHooks?: CombatHooks;
  readonly combatRng?: (state: MatchState, action: Action) => ISeededRng;
}

/**
 * The rng the combat hooks roll against for THIS action: the server-only salted `combatRng`
 * stream when supplied, else the public `rng` (fine for pure engine tests). Only consulted when
 * `combatHooks` is present, so the default (hooks absent) path never touches it.
 */
function combatRngFor(
  state: MatchState,
  action: Action,
  rng: ISeededRng,
  p: EngineProviders,
): ISeededRng {
  return p.combatRng ? p.combatRng(state, action) : rng;
}

