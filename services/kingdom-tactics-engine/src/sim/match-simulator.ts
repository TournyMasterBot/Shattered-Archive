/**
 * Run a full headless match. Each iteration the active side's policy chooses ONE action,
 * which is applied through the deterministic reducer; the side keeps acting until it (or
 * a guard) ends its turn. Terminates when the reducer flags the match `decided` or the
 * `turn` counter passes `maxTurns`. Pure w.r.t. inputs — all randomness comes from a
 * `createRng(seed)` stream, so the same config always yields the same `MatchResult`.
 *
 * Two anti-stall guards keep a bad policy from looping forever: a per-turn action cap
 * (`MAX_ACTIONS_PER_TURN`) forces an end-turn, and an illegal/no-op action (reducer
 * returns the same state) is converted into an end-turn.
 */
export function runMatch(cfg: MatchConfig): MatchResult {
  const rng = createRng(cfg.seed);
  const maxTurns = cfg.maxTurns ?? 200;
  const MAX_ACTIONS_PER_TURN = 500;

  let state = cfg.initial;
  let actions = 0;

  // Per-turn action counter, reset whenever the (side, turn) segment changes.
  let segmentSide: Side = state.activeSide;
  let segmentTurn = state.turn;
  let actionsThisTurn = 0;

  while (state.status === 'in-progress' && state.turn <= maxTurns) {
    const side = state.activeSide;
    if (side !== segmentSide || state.turn !== segmentTurn) {
      segmentSide = side;
      segmentTurn = state.turn;
      actionsThisTurn = 0;
    }

    const policy = cfg.policies[side];
    const forceEnd = !policy || actionsThisTurn >= MAX_ACTIONS_PER_TURN;
    const action: Action = forceEnd
      ? { type: 'end-turn', side }
      : policy.chooseAction(state, side, cfg.providers, rng);

    const next = applyAction(state, action, rng, cfg.providers);

    if (next === state) {
      // No-op (illegal action, or a rejected end-turn we should never see): end the turn
      // to guarantee forward progress. If even that is a no-op, bail to avoid an infinite loop.
      if (action.type === 'end-turn') break;
      const ended = applyAction(state, { type: 'end-turn', side }, rng, cfg.providers);
      if (ended === state) break;
      state = ended;
      actions++;
      continue;
    }

    state = next;
    actions++;
    actionsThisTurn++;
  }

  const decided = state.status === 'decided';
  return {
    winner: decided ? (state.winner ?? 'draw') : 'draw',
    decided,
    turns: state.turn,
    actions,
    reason: decided ? 'victory' : 'turn-limit',
    survivors: survivorsBySide(state),
    seed: cfg.seed,
  };
}
