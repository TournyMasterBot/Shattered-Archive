/** Living tokens per side (side index → count). */
function survivorsBySide(state: MatchState): Record<number, number> {
  const out: Record<number, number> = {};
  for (const t of state.tokens) {
    const alive = t.kind === 'unit' ? t.hp > 0 : t.hpPool > 0;
    if (alive) out[t.side] = (out[t.side] ?? 0) + 1;
  }
  return out;
}

