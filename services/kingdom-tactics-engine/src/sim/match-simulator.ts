import type { Action, MatchState, Side } from '../model/index.js';
import { createRng } from '../rng/index.js';
import { applyAction, type EngineProviders } from '../engine/game-engine.js';
import type { IAiPolicy } from '../ai/policy.js';
import type { MatchResult } from './types.js';

/** One seeded self-driving match: a policy per side, played to victory or a turn limit. */
export interface MatchConfig {
  readonly initial: MatchState;
  /** side index → the policy that controls it. A side with no policy simply ends its turns. */
  readonly policies: Readonly<Record<number, IAiPolicy>>;
  readonly providers: EngineProviders;
  readonly seed: number;
  /** Safety cap on the `turn` counter (default 200). */
  readonly maxTurns?: number;
}

