import ServerCache from "@shared/cache/server-cache";
import IAbility from "@shared/types/ability-types/ability";
import AbilityGroupType from "@shared/types/ability-types/ability-group-type";
import AbilityUsage from "@shared/types/ability-types/ability-usage";
import SkillSpellEffects from "@shared/types/ability-types/effects";

export class Intimidation implements IAbility {
  private static instance: Intimidation;

  name: string;
  helpFile: string;
  manualDescription?: string | undefined;
  duration?: number | undefined;
  effects?: SkillSpellEffects | undefined;
  group?: string | undefined;
  alternateKeyword?: string | undefined;
  recommendedHelpFileChanges?: string | undefined;
  abilityGroupType: AbilityGroupType;
  abilityUsage: AbilityUsage;

  constructor() {
    this.name = this.constructor.name;
    this.abilityGroupType = AbilityGroupType.Skills;
    this.abilityUsage = AbilityUsage.Active;
    this.helpFile = `intimidate
INTIMIDATE

Syntax: intimidate <target>

A pirate can learn to stare down an opponent, reducing the opponent's ability
to hit accurately.

The bigger a pirate's reputation, the more intimidating he or she can be.`;

    if (Intimidation.instance === undefined) {
      Intimidation.instance = this;
    }
  }

  // Method to get the single instance of the class
  public static GetInstance(): Intimidation {
    if (!this.instance) {
      this.instance = new this();
      ServerCache.Abilities[this.instance.name] = this.instance;
    }
    return this.instance;
  }

  // Method to get the class instance, used in the context of IAbility
  public Get<T>(): T {
    return Intimidation.GetInstance() as T;
  }
}

export default Intimidation;
