type CacheEntry = { expiresAt: number; value: unknown };

const MAPS_TTL_MS = 30 * 24 * 60 * 60 * 1000; // 30 days
const mapsCache = new Map<string, CacheEntry>();

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: getCached — Returns cached value if unexpired, otherwise deletes and returns null.
// @ai-hash: 440833f4
// ── END AI-METHOD ──
function getCached(key: string): unknown | null {
  const entry = mapsCache.get(key);
  if (!entry) return null;
  if (Date.now() >= entry.expiresAt) {
    mapsCache.delete(key);
    return null;
  }
  return entry.value;
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: setCached — Sets a cached value with expiration time in milliseconds.
// @ai-hash: 41aecd33
// ── END AI-METHOD ──
function setCached(key: string, value: unknown, ttlMs: number) {
  mapsCache.set(key, { value, expiresAt: Date.now() + ttlMs });
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
