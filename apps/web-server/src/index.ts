// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: buildUpstreamUrl — Constructs a complete upstream URL by combining a base URL with a path while ensuring proper formatting.
// @ai-hash: 61a92976
// ── END AI-METHOD ──
function buildUpstreamUrl(p: string): string | null {
  if (!SHATTEREDARCHIVE_BASE) return null;
  const base = SHATTEREDARCHIVE_BASE.replace(/\/+$/, '');
  const pathPart = p.replace(/^\/+/, '');
  return `${base}/${pathPart}`;
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: fetchJsonWithTimeout — Fetches JSON data with configurable timeout and returns structured success/error response.
// @ai-hash: a6201af0
// ── END AI-METHOD ──
async function fetchJsonWithTimeout(url: string, ms = 10_000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), ms);
  try {
    const r = await fetch(url, {
      method: 'GET',
      headers: { Accept: 'application/json' },
      signal: ac.signal,
    });

    if (!r.ok) {
      const text = await r.text().catch(() => '');
      return { ok: false as const, status: r.status, text };
    }

    const json = await r.json();
    return { ok: true as const, status: r.status, json };
  } catch (e: any) {
    return { ok: false as const, status: 0, text: String(e?.message ?? e ?? 'fetch failed') };
  } finally {
    clearTimeout(t);
  }
}

