// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: useMainContainer — Initializes Lua runtime and audio capabilities while managing three modal open states.
// @ai-hash: 889b4d02
// ── END AI-METHOD ──
export function useMainContainer() {
  useEffect(() => {
    if (typeof window !== 'undefined') {
      try {
        initBrowserLuaRunner();
      } catch (err) {
        console.error('[Lua] Failed to initialize Lua runtime:', err);
      }
    }
  }, []);

  useEffect(() => {
    ensureAudioRuntimeAttached();
  }, []);

  const [isConnectModalOpen, setIsConnectModalOpen] = useState(false);
  const openConnectModal = () => setIsConnectModalOpen(true);
  const closeConnectModal = () => setIsConnectModalOpen(false);

  const [isLibraryModalOpen, setIsLibraryModalOpen] = useState(false);
  const openLibraryModal = () => setIsLibraryModalOpen(true);
  const closeLibraryModal = () => setIsLibraryModalOpen(false);

  const [isEquipmentModalOpen, setIsEquipmentModalOpen] = useState(false);
  const openEquipmentModal = () => setIsEquipmentModalOpen(true);
  const closeEquipmentModal = () => setIsEquipmentModalOpen(false);

  return {
    isConnectModalOpen,
    openConnectModal,
    closeConnectModal,

    isLibraryModalOpen,
    openLibraryModal,
    closeLibraryModal,

    isEquipmentModalOpen,
    openEquipmentModal,
    closeEquipmentModal,
  };
}
