// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: ensureStyleTag — Ensures a style tag with the given ID exists in the document head, returning the element or null if unavailable.
// @ai-hash: 6505d691
// ── END AI-METHOD ──
function ensureStyleTag(id: string): HTMLStyleElement | null {
  if (typeof document === 'undefined') return null;

  const head = document.head || document.getElementsByTagName('head')[0];
  if (!head) return null;

  let el = document.getElementById(id);

  // If something else stole the id, delete it.
  if (el && el.tagName.toLowerCase() !== 'style') {
    el.parentElement?.removeChild(el);
    el = null;
  }

  const styleEl = (el as HTMLStyleElement) ?? document.createElement('style');
  styleEl.id = id;

  // Always move to end of <head> so it wins the cascade.
  head.appendChild(styleEl);

  return styleEl;
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
// @ai-method: applyUserCss — Updates the user CSS stylesheet with the provided CSS content.
// @ai-hash: feff094a
// ── END AI-METHOD ──
function applyUserCss(css: string) {
  const styleEl = ensureStyleTag(USER_CSS_STYLE_ID);
  if (!styleEl) return;

  styleEl.textContent = css || '';
}

// ── AI-METHOD ── regenerated by annotate_methods — do not hand-edit
