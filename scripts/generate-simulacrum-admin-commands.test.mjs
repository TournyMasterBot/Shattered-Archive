import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { DEFAULT_OUT, DEFAULT_SOURCE, generate, mergeRows, parseRows, runCli } from './generate-simulacrum-admin-commands.mjs';

const scratch = [];
after(() => {
  for (const dir of scratch) fs.rmSync(dir, { recursive: true, force: true });
});
function tmp() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gen-cmds-'));
  scratch.push(dir);
  return dir;
}

/** A small command table: one row per level symbol family, a comment, a numeric row and the end marker. */
const FIXTURE = `
const struct cmd_type cmd_table[] = {
    {"look", do_look, POS_RESTING, 0, LOG_NORMAL, 1},
    {"shout", do_shout, POS_RESTING, 3, LOG_NORMAL, 1},
    {"hero", do_hero, POS_RESTING, HE, LOG_NORMAL, 1},
    /*  { "old", do_old, POS_DEAD, L4, LOG_NORMAL, 1 }, */
    /* a block comment
       {"ghost", do_ghost, POS_DEAD, L1, LOG_NORMAL, 1},
    */
    {"advance", do_advance, POS_DEAD, ML, LOG_ALWAYS, 1},
    {"deny", do_deny, POS_DEAD, L1, LOG_ALWAYS, 1},
    {"goto", do_goto, POS_DEAD, L8, LOG_NORMAL, 1},
    {"stat", do_stat, POS_DEAD, IM, LOG_NORMAL, 1},
    {"teleport", do_transfer, POS_DEAD, L5, LOG_ALWAYS, 1},
    {"transfer", do_transfer, POS_DEAD, L5, LOG_ALWAYS, 1},
    {"reboo", do_reboo, POS_DEAD, L1, LOG_NORMAL, 0},
    {"reboot", do_reboot, POS_DEAD, L1, LOG_ALWAYS, 1},
    {"invis", do_invis, POS_DEAD, IM, LOG_NORMAL, 0},
    {"wizinvis", do_invis, POS_DEAD, IM, LOG_NORMAL, 1},
    {"dump", do_dump, POS_DEAD, ML, LOG_ALWAYS, 0},
    {"", 0, POS_DEAD, 0, LOG_NORMAL, 0}};
`;

test('each level symbol resolves to its trust, mortal rows and comments are left out', () => {
  const rows = parseRows(FIXTURE);
  const names = rows.map((r) => r.name);
  assert.deepEqual(names, ['advance', 'deny', 'goto', 'stat', 'teleport', 'transfer', 'reboo', 'reboot', 'invis', 'wizinvis', 'dump']);
  const level = Object.fromEntries(rows.map((r) => [r.name, r.level]));
  assert.equal(level.advance, 60);
  assert.equal(level.deny, 59);
  assert.equal(level.goto, 52);
  assert.equal(level.stat, 52);
  assert.equal(level.teleport, 55);
  assert.ok(!names.includes('look') && !names.includes('shout') && !names.includes('hero'), 'numeric and hero rows are mortal');
  assert.ok(!names.includes('old') && !names.includes('ghost'), 'commented rows are ignored, also inside a block comment');
});

test('rows sharing a handler merge and abbreviation rows become hidden aliases', () => {
  const commands = mergeRows(parseRows(FIXTURE));
  const byName = Object.fromEntries(commands.map((c) => [c.name, c]));
  assert.deepEqual(byName.transfer.aliases, ['teleport'], 'transfer is the shown name');
  assert.ok(!byName.teleport, 'teleport is not a second command');
  assert.deepEqual(byName.reboot.hiddenAliases, ['reboo']);
  assert.ok(!byName.reboo, 'reboo is never offered');
  assert.equal(byName.wizinvis.listed, true);
  assert.deepEqual(byName.wizinvis.hiddenAliases, ['invis']);
  assert.equal(byName.dump.listed, false, 'a hidden row with no listed parent stays a command, marked unlisted');
});

test('an unknown level symbol is an error naming the line and the command', () => {
  const bad = FIXTURE.replace('L1, LOG_ALWAYS, 1},\n    {"goto"', 'L9, LOG_ALWAYS, 1},\n    {"goto"');
  assert.throws(() => parseRows(bad), /line \d+: unknown level symbol L9 \(command deny\)/);
});

test('an unreadable row is an error naming the line', () => {
  assert.throws(() => parseRows(FIXTURE.replace('{"goto", do_goto,', '{"goto" do_goto,')), /line \d+: cannot read this command row/);
});

test('a missing table, an empty table and rows of one handler at two levels all fail loudly', () => {
  assert.throws(() => parseRows('int x;'), /cmd_table\[\] not found/);
  assert.throws(() => parseRows('const struct cmd_type cmd_table[] = {\n {"look", do_look, POS_DEAD, 0, LOG_NORMAL, 1},\n {"", 0, POS_DEAD, 0, LOG_NORMAL, 0}};'), /no privileged rows/);
  const split = 'const struct cmd_type cmd_table[] = {\n {"a", do_x, POS_DEAD, L1, LOG_NORMAL, 1},\n {"b", do_x, POS_DEAD, L2, LOG_NORMAL, 1},\n {"", 0, POS_DEAD, 0, LOG_NORMAL, 0}};';
  assert.throws(() => mergeRows(parseRows(split)), /different levels/);
});

test('the output is identical on two runs and carries no date (ADMIN-01)', () => {
  const a = generate(FIXTURE);
  const b = generate(FIXTURE);
  assert.equal(a, b);
  assert.doesNotMatch(a, /\b20\d\d-\d\d-\d\d\b/);
  assert.match(a, /rows-hash: [0-9a-f]{16}/);
  assert.match(a, /GENERATED by scripts\/generate-simulacrum-admin-commands\.mjs/);
});

test('the hash follows the privileged rows only, not the rest of the file', () => {
  const hashOf = (text) => /rows-hash: ([0-9a-f]+)/.exec(generate(text))[1];
  assert.equal(hashOf(FIXTURE), hashOf(FIXTURE.replace('{"look", do_look, POS_RESTING, 0,', '{"look", do_look, POS_DEAD, 0,')));
  assert.notEqual(hashOf(FIXTURE), hashOf(FIXTURE.replace('{"deny", do_deny, POS_DEAD, L1,', '{"deny", do_deny, POS_DEAD, L2,')));
});

test('the command line writes the file, --check passes on it and fails when it is stale', () => {
  const dir = tmp();
  const source = path.join(dir, 'interp.c');
  const out = path.join(dir, 'out.ts');
  fs.writeFileSync(source, FIXTURE);
  const io = { log() {}, error() {} };
  assert.equal(runCli(['--source', source, '--out', out], io), 0);
  assert.equal(fs.readFileSync(out, 'utf8'), generate(FIXTURE));
  assert.equal(runCli(['--source', source, '--out', out, '--check'], io), 0);
  fs.writeFileSync(out, '// stale\n');
  const errors = [];
  assert.equal(runCli(['--source', source, '--out', out, '--check'], { log() {}, error: (m) => errors.push(m) }), 1);
  assert.match(errors.join('\n'), /out of date/);
});

test('the command line reports a missing source, a bad argument and a generator failure', () => {
  const errors = [];
  const io = { log() {}, error: (m) => errors.push(m) };
  assert.equal(runCli(['--source', path.join(tmp(), 'nope.c')], io), 2);
  assert.equal(runCli(['--bogus'], io), 2);
  const dir = tmp();
  const source = path.join(dir, 'interp.c');
  fs.writeFileSync(source, 'int x;');
  assert.equal(runCli(['--source', source, '--out', path.join(dir, 'o.ts')], io), 1);
  assert.match(errors.join('\n'), /source not found/);
  assert.match(errors.join('\n'), /unknown argument --bogus/);
  assert.match(errors.join('\n'), /generator failed: cmd_table\[\] not found/);
});

test('the real command table yields 72 privileged rows and the committed file matches it', (t) => {
  if (!fs.existsSync(DEFAULT_SOURCE)) {
    t.skip(`the sibling repo is not present (${DEFAULT_SOURCE}); run on the owner's machine`);
    return;
  }
  const source = fs.readFileSync(DEFAULT_SOURCE, 'utf8');
  const rows = parseRows(source);
  assert.equal(rows.length, 72);
  const counts = {};
  for (const r of rows) counts[r.levelSymbol] = (counts[r.levelSymbol] ?? 0) + 1;
  assert.deepEqual(counts, { IM: 18, ML: 5, L1: 10, L2: 4, L3: 4, L4: 12, L5: 10, L6: 4, L7: 2, L8: 3 });
  assert.equal(fs.readFileSync(DEFAULT_OUT, 'utf8'), generate(source), 'run scripts/generate-simulacrum-admin-commands.mjs');
});
